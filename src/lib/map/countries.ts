export const COUNTRY_BY_ID: Record<string, CountryRecord> = Object.fromEntries(
  COUNTRIES.map((c) => [c.id, c]),
);

export function countryByGeoId(rawId: string | number | undefined, name?: string): CountryRecord | undefined {
  if (rawId != null && rawId !== "") {
    const padded = String(rawId).padStart(3, "0");
    if (COUNTRY_BY_ID[padded]) return COUNTRY_BY_ID[padded];
    if (COUNTRY_BY_ID[String(rawId)]) return COUNTRY_BY_ID[String(rawId)];
  }
  if (name && COUNTRY_BY_ID[name]) return COUNTRY_BY_ID[name];
  return COUNTRIES.find((c) => c.name === name);
}

export function rankedCountries(metric: MetricId): CountryRecord[] {
  return COUNTRIES.filter((c) => c[metric] != null).sort(
    (a, b) => (b[metric] as number) - (a[metric] as number),
  );
}

export function rankOf(id: string, metric: MetricId): { rank: number; total: number } | null {
  const ranked = rankedCountries(metric);
  const idx = ranked.findIndex((c) => c.id === id);
  if (idx < 0) return null;
  return { rank: idx + 1, total: ranked.length };
}
